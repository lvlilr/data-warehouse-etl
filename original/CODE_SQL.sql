-- =========================================
-- STEP 1: ORDERS_COPY
-- =========================================
DROP TABLE ORDERS_COPY;

CREATE TABLE ORDERS_COPY AS
SELECT * FROM OE.ORDERS;

UPDATE ORDERS_COPY
SET ORDER_MODE = UPPER(ORDER_MODE);

UPDATE ORDERS_COPY
SET SALES_REP_ID = 999
WHERE SALES_REP_ID IS NULL;

UPDATE ORDERS_COPY
SET PROMOTION_ID = 0
WHERE PROMOTION_ID IS NULL;

-- =========================================
-- STEP 2: T_DATE
-- =========================================
DROP TABLE T_DATE;

CREATE TABLE T_DATE(
ORDER_DATE DATE,
DAY_NO NUMBER(1),
DAY_NAME CHAR(10),
MONTH_NO NUMBER(2),
MONTH_NAME CHAR(10),
QUARTER NUMBER(1),
YYEAR NUMBER(4)
);

INSERT INTO T_DATE
SELECT DISTINCT
ORDER_DATE,
TO_NUMBER(TO_CHAR(ORDER_DATE,'D')),
TO_CHAR(ORDER_DATE,'DAY'),
TO_NUMBER(TO_CHAR(ORDER_DATE,'MM')),
TO_CHAR(ORDER_DATE,'MONTH'),
TO_NUMBER(TO_CHAR(ORDER_DATE,'Q')),
TO_NUMBER(TO_CHAR(ORDER_DATE,'YYYY'))
FROM OE.ORDERS;

-- =========================================
-- STEP 3: CUSTOMER_COPY
-- =========================================
DROP TABLE CUSTOMER_COPY;

CREATE TABLE CUSTOMER_COPY AS
SELECT
CUSTOMER_ID,
CUST_FIRST_NAME,
CUST_LAST_NAME,
GENDER,
CUST_EMAIL,
NLS_TERRITORY,
CREDIT_LIMIT,
ACCOUNT_MGR_ID
FROM OE.CUSTOMERS;

ALTER TABLE CUSTOMER_COPY ADD TURNOVER NUMBER(12,2);
ALTER TABLE CUSTOMER_COPY ADD CUST_TYPE VARCHAR2(1);

UPDATE CUSTOMER_COPY C
SET TURNOVER =
(
SELECT SUM(O.ORDER_TOTAL)
FROM OE.ORDERS O
WHERE O.CUSTOMER_ID = C.CUSTOMER_ID
);

DECLARE
AVG_TURN NUMBER;
BEGIN
SELECT AVG(TURNOVER) INTO AVG_TURN FROM CUSTOMER_COPY;

FOR REC IN (SELECT * FROM CUSTOMER_COPY) LOOP
IF REC.TURNOVER >= AVG_TURN THEN
UPDATE CUSTOMER_COPY SET CUST_TYPE='A'
WHERE CUSTOMER_ID=REC.CUSTOMER_ID;

ELSIF REC.TURNOVER >= AVG_TURN/2 THEN
UPDATE CUSTOMER_COPY SET CUST_TYPE='B'
WHERE CUSTOMER_ID=REC.CUSTOMER_ID;

ELSE
UPDATE CUSTOMER_COPY SET CUST_TYPE='C'
WHERE CUSTOMER_ID=REC.CUSTOMER_ID;
END IF;
END LOOP;
END;
/

-- =========================================
-- STEP 4: T_SALESMAN
-- =========================================
DROP TABLE T_SALESMAN;

CREATE TABLE T_SALESMAN AS
SELECT DISTINCT
NVL(SALES_REP_ID,999) AS SALES_REP_ID,
'NAME-' || NVL(SALES_REP_ID,999) AS SNAME
FROM ORDERS_COPY;

-- =========================================
-- STEP 5: DIMENSIONS
-- =========================================

-- D_TIME
DROP TABLE D_TIME CASCADE CONSTRAINTS;

CREATE TABLE D_TIME AS
SELECT DISTINCT * FROM T_DATE;

ALTER TABLE D_TIME
ADD CONSTRAINT PK_D_TIME PRIMARY KEY (ORDER_DATE);

-- D_CUSTOMERS
DROP TABLE D_CUSTOMERS CASCADE CONSTRAINTS;

CREATE TABLE D_CUSTOMERS AS
SELECT DISTINCT
CUSTOMER_ID,
CUST_FIRST_NAME,
CUST_LAST_NAME,
CUST_TYPE,
TURNOVER
FROM CUSTOMER_COPY;

ALTER TABLE D_CUSTOMERS
ADD CONSTRAINT PK_D_CUSTOMERS PRIMARY KEY (CUSTOMER_ID);

-- D_SALESMAN
DROP TABLE D_SALESMAN CASCADE CONSTRAINTS;

CREATE TABLE D_SALESMAN AS
SELECT * FROM T_SALESMAN;

ALTER TABLE D_SALESMAN
ADD CONSTRAINT PK_D_SALESMAN PRIMARY KEY (SALES_REP_ID);

-- D_ORDERS
DROP TABLE D_ORDERS CASCADE CONSTRAINTS;

CREATE TABLE D_ORDERS AS
SELECT
ORDER_ID,
ORDER_MODE,
ORDER_STATUS
FROM ORDERS_COPY;

ALTER TABLE D_ORDERS
ADD CONSTRAINT PK_D_ORDERS PRIMARY KEY (ORDER_ID);

-- =========================================
-- STEP 6: FACT TABLE
-- =========================================
DROP TABLE F_ORDERS CASCADE CONSTRAINTS;

CREATE TABLE F_ORDERS(
F_ORDERS_ID NUMBER,
ORDER_ID NUMBER,
CUSTOMER_ID NUMBER,
ORDER_DATE DATE,
SALES_REP_ID NUMBER,
ORDER_AMOUNT NUMBER,
CONSTRAINT PK_F_ORDERS PRIMARY KEY(F_ORDERS_ID)
);

DROP SEQUENCE SEQ_F_ORDERS;

CREATE SEQUENCE SEQ_F_ORDERS START WITH 1;

INSERT INTO F_ORDERS
SELECT
SEQ_F_ORDERS.NEXTVAL,
ORDER_ID,
CUSTOMER_ID,
ORDER_DATE,
SALES_REP_ID,
ORDER_TOTAL
FROM ORDERS_COPY;

-- =========================================
-- STEP 7: ANALYSIS
-- =========================================

-- Total Sales
SELECT SUM(ORDER_AMOUNT) FROM F_ORDERS;

-- Sales per Customer per Year
SELECT
F.CUSTOMER_ID,
D.YYEAR,
SUM(F.ORDER_AMOUNT)
FROM F_ORDERS F
JOIN D_TIME D ON F.ORDER_DATE = D.ORDER_DATE
GROUP BY F.CUSTOMER_ID, D.YYEAR;

-- Orders greater than 5000
SELECT COUNT(*) FROM F_ORDERS WHERE ORDER_AMOUNT > 5000;

-- Percentage of Order Mode (FINAL WORKING VERSION)
SELECT
OC.ORDER_MODE,
ROUND(
SUM(OC.ORDER_TOTAL) /
(SELECT SUM(ORDER_TOTAL) FROM ORDERS_COPY) * 100,
2
) AS PERCENTAGE
FROM ORDERS_COPY OC
GROUP BY OC.ORDER_MODE;
